// Writes cer/src/tzdata.rs: the IANA time zone database as CEr reads it
// (tz.rs), from the host's compiled zoneinfo (TZif files and tzdata.zi).
//
//   node cer/tools/gen-tzdata.cjs [/usr/share/zoneinfo]
//
// One line per zone (its links after it, by comma):
//   names;footer;first offset;transitions;names of its offsets
// footer is the TZif POSIX TZ rule that holds after the last transition,
// offsets are seconds east of UTC and the transitions are
// <seconds since the previous one>:<offset> in base 36, the first counted
// from 1800-01-01 (earlier ones are dropped; the first offset holds before).
// Transitions from 2026 on are left to the footer, which gives the same, and
// ones that do not change the offset (a name only) are dropped. The names
// are en-US's from the host's ICU (Date.prototype.toString, timeZoneName),
// for January and July 2026: offset|long|short, twice; a short name that is
// the GMT+h form is left empty.
"use strict";
const fs = require("fs");
const path = require("path");

const ZI = process.argv[2] || "/usr/share/zoneinfo";
const OUT = path.join(__dirname, "..", "src", "tzdata.rs");
const FROM = -5364662400; // 1800-01-01: local mean time and the first standard offsets
const UNTIL = 1767225600; // 2026-01-01

const zi = fs.readFileSync(path.join(ZI, "tzdata.zi"), "utf8");
const version = (/^# version (\S+)/m.exec(zi) || [])[1] || "unknown";
const zones = [];
const links = new Map();
for (const line of zi.split("\n")) {
  const p = line.split(/\s+/);
  if (p[0] === "Z") zones.push(p[1]);
  if (p[0] === "L") {
    if (!links.has(p[1])) links.set(p[1], []);
    links.get(p[1]).push(p[2]);
  }
}

function tzif(name) {
  const d = fs.readFileSync(path.join(ZI, name));
  const hdr = (o) => ({ isut: d.readInt32BE(o + 20), isstd: d.readInt32BE(o + 24), leap: d.readInt32BE(o + 28), time: d.readInt32BE(o + 32), type: d.readInt32BE(o + 36), chars: d.readInt32BE(o + 40) });
  let h = hdr(0);
  let o = 44 + h.time * 5 + h.type * 6 + h.chars + h.leap * 8 + h.isstd + h.isut;
  h = hdr(o);
  o += 44;
  const times = [];
  for (let i = 0; i < h.time; i++) times.push(Number(d.readBigInt64BE(o + 8 * i)));
  o += 8 * h.time;
  const idx = [];
  for (let i = 0; i < h.time; i++) idx.push(d[o + i]);
  o += h.time;
  const types = [];
  for (let i = 0; i < h.type; i++) types.push(d.readInt32BE(o + 6 * i));
  o += 6 * h.type + h.chars + h.leap * 12 + h.isstd + h.isut;
  const footer = d.slice(o).toString("utf8").trim();
  return { times, offs: idx.map((i) => types[i]), first: types[0], footer };
}

const b36 = (n) => (n < 0 ? "-" + (-n).toString(36) : n.toString(36));
const lines = [];
const known = (z) => {
  try {
    new Intl.DateTimeFormat("en-US", { timeZone: z });
    return true;
  } catch (e) {
    return false;
  }
};
// (a zone the browser's ICU does not take, Factory, is left out)
for (const z of zones.sort().filter(known)) {
  const t = tzif(z);
  let off = t.first;
  const tr = [];
  let prev = FROM;
  for (let i = 0; i < t.times.length; i++) {
    const at = t.times[i];
    // (a footer without daylight saving rules over transitions that go on,
    // Morocco's Ramadan, keeps them)
    if (at >= UNTIL && t.footer && t.footer.includes(",")) break;
    if (at < FROM) {
      off = t.offs[i];
      continue;
    }
    if (tr.length === 0 ? t.offs[i] === off : t.offs[i] === tr[tr.length - 1][1]) continue;
    tr.push([at, t.offs[i]]);
  }
  const parts = tr.map(([at, o]) => {
    const s = b36(at - prev) + ":" + b36(o);
    prev = at;
    return s;
  });
  const names = [z].concat((links.get(z) || []).filter(known).sort());
  const shown = [0, 6].map((m) => {
    const at = new Date(Date.UTC(2026, m, 15));
    const nm = (style) => new Intl.DateTimeFormat("en-US", { timeZone: z, timeZoneName: style }).formatToParts(at).find((p) => p.type === "timeZoneName").value;
    const long = nm("long"), short = nm("short"), gmt = nm("shortOffset");
    // the zone's offset then, in seconds, from the GMT+h:mm form
    const g = /^GMT(?:([+-])(\d+)(?::(\d+))?)?$/.exec(gmt);
    const offs = g && g[1] ? (g[1] === "-" ? -1 : 1) * ((+g[2]) * 3600 + (+(g[3] || 0)) * 60) : 0;
    return b36(offs) + "|" + long + "|" + (short === gmt ? "" : short);
  });
  if (shown[1].split("|")[0] === shown[0].split("|")[0]) shown.pop();
  lines.push(names.join(",") + ";" + t.footer + ";" + b36(off) + ";" + parts.join(",") + ";" + shown.join("|"));
}

let rs = `// SPDX-License-Identifier: AGPL-3.0-or-later
//! The IANA time zone database ${version}, as tz.rs reads it: a line per
//! zone, "names;footer;first offset;transitions;names" (cer/tools/gen-tzdata.cjs
//! says more). Built in with the \`tzdata\` feature (on by default); without
//! it lib.rs takes tzdata_none.rs, where the only zone is UTC.
//!
//! GENERATED by cer/tools/gen-tzdata.cjs from the host's zoneinfo.

/// the database's version
pub fn version() -> String {
    String::from("${version}")
}

/// the zones, a line each
pub fn zones() -> String {
    let mut s = String::new();
`;
let chunk = "";
const flush = () => {
  if (chunk) rs += `    s.push_str(${JSON.stringify(chunk)});\n`;
  chunk = "";
};
for (const l of lines) {
  chunk += l + "\n";
  if (chunk.length > 3000) flush();
}
flush();
rs += `    s
}
`;
fs.writeFileSync(OUT, rs);
console.log(`${lines.length} zones, ${rs.length} bytes -> ${OUT}`);
