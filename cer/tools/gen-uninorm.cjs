// Writes cer/src/uninorm.rs, the tables of String.prototype.normalize, from
// the engine's committed ones (engine/UnicodeNorm.rgr, whose generator
// tools/gen-unicode-norm-tables.cjs says where every number comes from).
//
//   node cer/tools/gen-uninorm.cjs
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const SRC = path.join(ROOT, "engine", "UnicodeNorm.rgr");
const OUT = path.join(ROOT, "cer", "src", "uninorm.rs");

const text = fs.readFileSync(SRC, "utf8");
function table(name) {
  const m = new RegExp("static sfn " + name + ":\\[int\\] \\(\\) \\{\\s*return \\(\\[\\]([\\s\\S]*?)\\)\\s*\\}").exec(text);
  if (!m) throw new Error("no table " + name + " in " + SRC);
  return m[1].trim().split(/\s+/).map(Number);
}
// a table as Rust string pieces of space-separated numbers, a line each
function rust(name, nums, doc) {
  const lines = [];
  for (let i = 0; i < nums.length; i += 24) lines.push(nums.slice(i, i + 24).join(" "));
  return `/// ${doc}\npub fn ${name}() -> String {\n    let mut s = String::new();\n` +
    lines.map((l) => `    s.push_str("${l} ");\n`).join("") + "    s\n}\n";
}

const out = `// SPDX-License-Identifier: AGPL-3.0-or-later
//! The canonical normalization tables (NFC, NFD) of
//! String.prototype.normalize, as numbers separated by spaces; decoded on
//! first use. Hangul is not here: it is arithmetic (Unicode 3.12).
//!
//! GENERATED by cer/tools/gen-uninorm.cjs from engine/UnicodeNorm.rgr.

${rust("decomp", table("decomp"), "(code point, count, points…): the canonical decomposition, fully expanded")}
${rust("ccc_runs", table("cccRuns"), "(first, last, class): the canonical combining classes, renumbered in order")}
${rust("compose", table("compose"), "(starter, mark, composite): the pairs NFC puts together")}`;
fs.writeFileSync(OUT, out);
console.log("wrote " + path.relative(ROOT, OUT));
